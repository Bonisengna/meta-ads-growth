alter table public.meta_hub_leads enable row level security;
alter table public.meta_hub_identificadores enable row level security;
alter table public.meta_hub_eventos enable row level security;
alter table public.meta_hub_mapa_eventos_meta enable row level security;
alter table public.meta_hub_fila_capi enable row level security;
alter table public.meta_hub_publicos enable row level security;
alter table public.meta_hub_publico_membros enable row level security;

comment on table public.meta_hub_fila_capi is
'Outbox idempotente para envio de eventos de funil à Meta Conversions API.';

comment on table public.meta_hub_publico_membros is
'Controle de sincronização de leads elegíveis com Custom Audiences da Meta.';
